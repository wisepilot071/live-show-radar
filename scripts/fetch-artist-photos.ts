/**
 * Finds a real, freely licensed photo for each curated artist and self-hosts it.
 *   npx vite-node --config vitest.config.ts scripts/fetch-artist-photos.ts
 *
 * Chain (no guessing): MusicBrainz artist → its Wikidata link → Wikidata "image"
 * (P18) → the Wikimedia Commons file → licence + author from Commons metadata.
 * Artists without that chain get NO photo (the UI shows initials). Only licences
 * that allow reuse with attribution are accepted (CC0 / public domain / CC BY / CC BY-SA).
 * Output: public/images/artists/<slug>.webp (square, 320px) + src/data/artist-photos.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import sharp from "sharp";
import { CURATED_ARTISTS } from "../src/data/curated-artists";

const UA = "LiveShowRadar/1.0 (artist photo credits; https://live-show-radar.vercel.app)";
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
const strip = (html: string | undefined) => (html ?? "").replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();

async function json<T>(url: string): Promise<T> {
  const res = await fetch(url, { headers: { "User-Agent": UA, Accept: "application/json" } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return (await res.json()) as T;
}

async function wikidataFor(mbid: string | null, name: string): Promise<string | null> {
  if (mbid) {
    const mb = await json<{ relations?: Array<{ type: string; url?: { resource: string } }> }>(
      `https://musicbrainz.org/ws/2/artist/${mbid}?inc=url-rels&fmt=json`,
    );
    await sleep(1100); // MusicBrainz: max 1 request/second
    const wd = mb.relations?.find((r) => r.type === "wikidata")?.url?.resource;
    return wd?.split("/").pop() ?? null;
  }
  // No MBID: no photo. A name search once matched the wrong "Divine" (an American performer,
  // not the Indian rapper), so identity must come from MusicBrainz.
  void name;
  return null;
}

const OK_LICENCE = /^(cc0|public domain|pd|cc[ -]by(-sa)?[ -]?\d|cc by(-sa)? \d)/i;

async function main() {
  mkdirSync("public/images/artists", { recursive: true });
  const out: Record<string, unknown> = {};
  for (const a of CURATED_ARTISTS) {
    try {
      const qid = await wikidataFor(a.musicbrainzId, a.name);
      if (!qid) {
        console.log(`-  ${a.name}: no Wikidata link`);
        continue;
      }
      const wd = await json<{ claims: Record<string, Array<{ mainsnak: { datavalue?: { value: string } } }>> }>(
        `https://www.wikidata.org/w/api.php?action=wbgetclaims&entity=${qid}&property=P18&format=json`,
      );
      const file = wd.claims.P18?.[0]?.mainsnak.datavalue?.value;
      if (!file) {
        console.log(`-  ${a.name}: ${qid} has no image`);
        continue;
      }
      const info = await json<{
        query: { pages: Record<string, { imageinfo?: Array<{ thumburl: string; descriptionurl: string; extmetadata: Record<string, { value: string }> }> }> };
      }>(
        `https://commons.wikimedia.org/w/api.php?action=query&titles=${encodeURIComponent(`File:${file}`)}&prop=imageinfo&iiprop=url|extmetadata&iiurlwidth=640&format=json`,
      );
      const ii = Object.values(info.query.pages)[0]?.imageinfo?.[0];
      if (!ii) continue;
      const licence = strip(ii.extmetadata.LicenseShortName?.value);
      if (!OK_LICENCE.test(licence)) {
        console.log(`-  ${a.name}: licence "${licence}" not accepted`);
        continue;
      }
      const img = await fetch(ii.thumburl, { headers: { "User-Agent": UA } });
      if (!img.ok) throw new Error(`image ${img.status}`);
      await sharp(Buffer.from(await img.arrayBuffer()))
        .resize(320, 320, { fit: "cover", position: sharp.strategy.attention })
        .webp({ quality: 74 })
        .toFile(`public/images/artists/${a.slug}.webp`);
      out[a.slug] = {
        name: a.name,
        src: `/images/artists/${a.slug}.webp`,
        author: strip(ii.extmetadata.Artist?.value).slice(0, 120) || "Unknown author",
        licence,
        licenceUrl: ii.extmetadata.LicenseUrl?.value ?? null,
        sourceUrl: ii.descriptionurl,
        wikidata: qid,
      };
      console.log(`✓  ${a.name}: ${licence}`);
      await sleep(300);
    } catch (e) {
      console.log(`!  ${a.name}: ${(e as Error).message}`);
    }
  }
  const body = `/**
 * Artist photos — GENERATED by scripts/fetch-artist-photos.ts on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
 * Each photo is the artist's own Wikidata image (linked from their MusicBrainz record), from
 * Wikimedia Commons under the licence shown; author and licence must be credited wherever it appears
 * (see ArtistPhotoCredits). Artists missing here get an initials avatar — never a substitute photo.
 */
export interface ArtistPhoto {
  name: string;
  src: string;
  author: string;
  licence: string;
  licenceUrl: string | null;
  sourceUrl: string;
  wikidata: string;
}

export const ARTIST_PHOTOS: Record<string, ArtistPhoto> = ${JSON.stringify(out, null, 2)};
`;
  writeFileSync("src/data/artist-photos.ts", body);
  console.log(`\n${Object.keys(out).length}/${CURATED_ARTISTS.length} artists have a licensed photo`);
}

void main();
