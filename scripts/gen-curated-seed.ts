/**
 * Generates db/migrations/0007_seed_curated_artists.sql from src/data/curated-artists.ts
 * (single source of truth). Run: npx vite-node scripts/gen-curated-seed.ts
 */
import { writeFileSync } from "node:fs";
import { CURATED_ARTISTS, CURATED_LIST_ENTRIES, catalogueKeyOf } from "../src/data/curated-artists";

const q = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const artistRows = CURATED_ARTISTS.map(
  (a) =>
    `  (${q(catalogueKeyOf(a))}, ${q(a.name)}, ${q(a.country)}, ${a.musicbrainzId ? `${q(a.musicbrainzId)}::uuid` : "null"}, ${q(a.musicbrainzId ? "musicbrainz" : "curated")}, ${q(a.category)})`,
);
const bySlug = new Map(CURATED_ARTISTS.map((a) => [a.slug, a]));
const listRows = CURATED_LIST_ENTRIES.map((e) => {
  const a = bySlug.get(e.slug);
  if (!a) throw new Error(`No catalogue artist for list entry ${e.entryName}`);
  return `  (${q(e.list)}, ${e.position}, ${q(e.entryName)}, ${q(catalogueKeyOf(a))})`;
});

const sql = `-- 0007: seed the curated catalogue (GENERATED by scripts/gen-curated-seed.ts — do not edit by hand).
-- ${CURATED_LIST_ENTRIES.length} list entries -> ${CURATED_ARTISTS.length} unique artists. Idempotent: re-running changes nothing.
-- Existing rows (same catalogue key, e.g. an artist someone already follows) keep their data; only category is set.

insert into radar.artists (catalogue_key, name, country, musicbrainz_id, origin, category)
values
${artistRows.join(",\n")}
on conflict (catalogue_key) do update set category = excluded.category, updated_at = now();

insert into radar.curated_artist_lists (list_key, position, entry_name, artist_id)
select v.list_key, v.position, v.entry_name, a.id
from (values
${listRows.join(",\n")}
) as v(list_key, position, entry_name, catalogue_key)
join radar.artists a on a.catalogue_key = v.catalogue_key
on conflict (list_key, position) do update set entry_name = excluded.entry_name, artist_id = excluded.artist_id;
`;
writeFileSync(new URL("../db/migrations/0007_seed_curated_artists.sql", import.meta.url), sql);
console.log(`wrote ${CURATED_ARTISTS.length} artists, ${CURATED_LIST_ENTRIES.length} list entries`);
